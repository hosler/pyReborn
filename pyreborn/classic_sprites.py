SPRITE_COUNT = len(SPRITE_RECTS)


def sprite_rect(index):
    """Return (x, y, w, h) for a sprite index, or None when out of range.

    Out-of-range indices draw nothing in the original (TPlayer.cpp:5323
    gates on ``sprite < 0x164``).
    """
    if not isinstance(index, int) or not 0 <= index < SPRITE_COUNT:
        return None
    return SPRITE_RECTS[index]


def draw_sprite(sprite_mgr, index):
    """Return the Surface for a classic sprite index, or None.

    None when the index is out of range, the rect is empty, or sprites.png has
    not been found/streamed yet (callers just skip the frame).
    """
    rect = sprite_rect(index)
    if rect is None or rect[2] <= 0 or rect[3] <= 0:
        return None
    return sprite_mgr.get_sprite(SPRITES_SHEET, *rect)


def swamp_index(tile_type):
    """Swamp slot for a ground tile type, or -1 (TServerLevel.cpp:2573-2582:
    types 6-9 map to slots 0-3)."""
    return tile_type - 6 if 6 <= tile_type <= 9 else -1


def swamp_sprite(slot, step_parity, timer_calls):
    """Sprite index drawn over the feet for a swamp slot, or None.

    Slots 0/1 follow the walk-step parity (+0/+1), slots 2/3 blink every two
    ticks, TServerPlayer.cpp:1271-1278 and the blink at :24-28:
    0 -> 22/23, 1 -> 352/353, 2 -> 150/151, 3 -> 354/355.
    """
    if slot == 0:
        return 22 + step_parity
    if slot == 1:
        return 352 + step_parity
    if slot == 2:
        return 150 + ((timer_calls // 2) & 1)
    if slot == 3:
        return 354 + ((timer_calls // 2) & 1)
    return None
